"""Validate the supplied CSV and deterministically generate an idempotent SQL seed.

Run from any directory: python scripts/build_seed.py
Allergen inference is the requested name-based heuristic, not a food safety guarantee.
"""
from __future__ import annotations

import argparse
import csv
from decimal import Decimal, InvalidOperation
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "api"))
from engine.categories import GROUPS, KIND_TO_DEFAULT_GROUP, display_group  # noqa: E402

NUTRIENTS = ("kcal", "protein", "carbs", "fat")
TASTES = ("sweet", "salty", "sour", "spicy")
COLUMNS = ("category", "name", *NUTRIENTS, *TASTES, "priority")


def allergens_for(category: str, name: str) -> list[str]:
    n = name.casefold()
    tags: set[str] = set()

    def starts(*terms: str) -> bool:
        # Match the start of any word (including names in parentheses), not
        # arbitrary interior substrings; prefixes also cover plurals.
        return any(re.search(r"(?<!\w)" + re.escape(term), n) for term in terms)

    if category.casefold() == "dairy" and n != "coconut milk":
        tags.add("milk")
    for terms, tag in [
        (("peanut",), "peanuts"),
        (("almond", "cashew", "pistachio", "walnut", "pine nut", "hazelnut"), "tree_nuts"),
        (("sesame",), "sesame"),
        (("egg", "mayonnaise"), "eggs"),
        (("fish",), "fish"),
        (("prawn", "oyster"), "shellfish"),
        (("mustard", "achar"), "mustard"),
        (("besan", "roasted chana", "papad"), "legumes"),
        (("tomato",), "tomato"),
        (("brinjal", "baingan"), "brinjal"),
        (("mango",), "mango"),
        (("orange", "malta", "kinnow", "sweet lime", "mosambi", "lemon", "nimbu", "amla"), "citrus"),
        (("banana",), "banana"),
        (("strawberr",), "strawberry"),
        (("coconut",), "coconut"),
        (("corn", "makai"), "corn"),
    ]:
        if starts(*terms):
            tags.add(tag)
    if n not in {"cornmeal (makai atta)", "millet flour (bajra atta)"} and starts(
        "atta", "maida", "refined flour", "suji", "semolina", "bread", "bun", "noodles",
        "seviyan", "vermicelli", "oats", "macaroni", "spaghetti", "dalia", "barley", "samosa"
    ):
        tags.add("gluten")
    if starts("soy sauce"):
        tags.update(("soy", "gluten"))
    if starts("soya chunks"):
        tags.add("soy")
    if category.casefold() == "pulses & nuts" and any(
        term in n for term in ("dal", "chana", "chickpea", "beans", "moong", "peas", "mash", "rajma", "lobia", "soya")
    ):
        tags.add("legumes")
    return sorted(tags)


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def load_rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames != list(COLUMNS):
            raise ValueError(f"Expected columns in order: {', '.join(COLUMNS)}")
        rows = list(reader)
    if not rows:
        raise ValueError("CSV is empty")
    seen: set[str] = set()
    for line, row in enumerate(rows, 2):
        if None in row or any(v is None or not v.strip() for v in row.values()):
            raise ValueError(f"Line {line}: missing or extra fields")
        row.update({k: v.strip() for k, v in row.items()})
        if row["name"].casefold() in seen:
            raise ValueError(f"Line {line}: duplicate ingredient name")
        seen.add(row["name"].casefold())
        for field in (*NUTRIENTS, *TASTES, "priority"):
            try:
                value = Decimal(row[field])
            except InvalidOperation as exc:
                raise ValueError(f"Line {line}: invalid {field}") from exc
            if not value.is_finite() or value < 0:
                raise ValueError(f"Line {line}: invalid {field}")
            if field in (*TASTES, "priority"):
                low, high = (1, 5) if field == "priority" else (0, 10)
                if value != value.to_integral_value() or not low <= value <= high:
                    raise ValueError(f"Line {line}: {field} out of range")
            row[field] = format(value, "f")
    return rows


def build_seed(source: Path) -> str:
    rows = load_rows(source)
    lines = ["-- Generated by scripts/build_seed.py; do not edit by hand.",
             "-- Nutrition per 100g is supplied data, not independently verified.", "begin;", ""]
    # The database holds the display categories people browse; the CSV's 8 kinds stay in the engine.
    for group in GROUPS:
        lines.append(f"insert into public.categories(name) values ({quote(group)}) on conflict (name) do nothing;")
    fields = ("name", "category_id", *NUTRIENTS, *TASTES, "allergens", "priority")
    updates = ", ".join(f"{field} = excluded.{field}" for field in fields[1:])
    for row in rows:
        tags = allergens_for(row["category"], row["name"])
        group = display_group(row["category"], row["name"])
        values = [quote(row["name"]), f"(select id from public.categories where name = {quote(group)})",
                  *(row[k] for k in (*NUTRIENTS, *TASTES)),
                  "array[" + ",".join(map(quote, tags)) + "]::text[]", row["priority"]]
        lines.append(f"insert into public.ingredients({', '.join(fields)}) values ({', '.join(values)}) on conflict (name) do update set {updates};")
    lines.extend(["", "commit;", ""])
    return "\n".join(lines)


ALLERGEN_TAGS = ("milk", "gluten", "eggs", "peanuts", "tree_nuts", "sesame", "fish", "shellfish", "soy", "mustard",
                 "legumes", "tomato", "brinjal", "mango", "citrus", "banana", "strawberry", "coconut", "corn")


def build_allergen_migration(source: Path) -> str:
    """UPDATE-only migration: re-tags existing ingredient rows by name, never inserts."""
    rows = [r for r in load_rows(source) if r["name"] not in NEW_INGREDIENTS]  # 0004 predates them
    values = ",\n".join(f"  ({quote(row['name'])}, array[{','.join(map(quote, allergens_for(row['category'], row['name'])))}]::text[])"
                        for row in rows)
    return "\n".join([
        "-- Generated by scripts/build_seed.py; do not edit by hand.",
        "-- Re-tags existing ingredients with the 19 allergen tags. Safe to run more than once:",
        "-- it only UPDATEs rows matched by name and never inserts or deletes.",
        "begin;",
        "create or replace function public.valid_allergens(tags text[]) returns boolean",
        "language sql immutable set search_path = '' as $$",
        "  select tags is not null and array_position(tags, null) is null",
        "    and tags <@ array[" + ",".join(map(quote, ALLERGEN_TAGS)) + "]::text[];",
        "$$;",
        "update public.ingredients as i set allergens = v.tags",
        "from (values",
        values,
        ") as v(name, tags)",
        "where i.name = v.name and i.allergens is distinct from v.tags;",
        "commit;",
        "",
    ])


def build_category_migration(source: Path) -> str:
    """Move a live database from the 8 source categories to the 13 display categories, keeping all data."""
    rows = load_rows(source)
    seed_lines = [line for line in build_seed(source).splitlines() if line.startswith("insert into public.ingredients")]
    moves = ",\n".join(f"  ({quote(r['name'])}, {quote(display_group(r['category'], r['name']))})" for r in rows)
    old = [k for k in KIND_TO_DEFAULT_GROUP if k not in GROUPS]
    return "\n".join([
        "-- Generated by scripts/build_seed.py; do not edit by hand.",
        "-- Clearer categories: 8 source categories -> 13 display categories (see api/engine/categories.py),",
        "-- plus ingredients added since (Burger Buns). Safe to run more than once. Nothing is deleted except",
        "-- old category rows that are left empty; pantry, saved recipes and recipe lines are untouched.",
        "begin;",
        *(f"insert into public.categories(name) values ({quote(g)}) on conflict (name) do nothing;" for g in GROUPS),
        "",
        "-- New ingredients (existing rows are left exactly as they are).",
        *(line.split(" on conflict ")[0] + " on conflict (name) do nothing;" for line in seed_lines
          if any(f"values ({quote(n)}," in line for n in NEW_INGREDIENTS)),
        "",
        "-- Every known ingredient into its display category.",
        "update public.ingredients as i set category_id = c.id",
        "from (values",
        moves,
        ") as v(name, grp) join public.categories c on c.name = v.grp",
        "where i.name = v.name and i.category_id is distinct from c.id;",
        "",
        "-- Ingredients an admin added to an old category: its closest display category.",
        *(f"update public.ingredients set category_id = (select id from public.categories where name = "
          f"{quote(KIND_TO_DEFAULT_GROUP[k])}) where category_id = (select id from public.categories where name = {quote(k)});"
          for k in old),
        "delete from public.categories c where c.name in (" + ", ".join(map(quote, old)) + ")",
        "  and not exists (select 1 from public.ingredients i where i.category_id = c.id);",
        "commit;",
        "",
    ])


NEW_INGREDIENTS = ("Burger Buns (Bun)",)  # added after the original 260; inserted by the category migration


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, default=ROOT / "supabase/seed/ingredients.csv")
    parser.add_argument("--output", type=Path, default=ROOT / "supabase/seed/seed.sql")
    parser.add_argument("--migration", type=Path, default=None,
                        help="also rewrite the allergen migration (0004 is already applied, so only on purpose)")
    parser.add_argument("--category-migration", type=Path, default=ROOT / "supabase/migrations/0006_categories.sql")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build_seed(args.csv), encoding="utf-8")
    args.category_migration.write_text(build_category_migration(args.csv), encoding="utf-8")
    if args.migration:
        args.migration.write_text(build_allergen_migration(args.csv), encoding="utf-8")
    print(f"Wrote {args.output} and {args.category_migration}")


if __name__ == "__main__":
    main()
