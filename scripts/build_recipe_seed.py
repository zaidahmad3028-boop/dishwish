"""Generate supabase/seed/recipes.sql from api/engine/curated_data.py.

Run from any directory: python scripts/build_recipe_seed.py
The seed is idempotent and never overwrites admin edits: recipes are inserted only when their
slug is new (with their ingredients and steps), and compatibility edges only when the pair is new.
Run it after migrations/0005_admin_recipes.sql and seed/seed.sql.
"""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "api"))

from engine.data import load_ingredients  # noqa: E402
from engine.suitability import bundled_recipes, cooccurrence_edges  # noqa: E402


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def ingredient_id(name: str) -> str:
    return f"(select id from public.ingredients where name = {quote(name)})"


def build() -> str:
    catalog = {i.name: i for i in load_ingredients()}
    recipes = bundled_recipes()
    lines = ["-- Generated by scripts/build_recipe_seed.py from api/engine/curated_data.py; do not edit by hand.",
             "-- Development and demonstration catalog. Inserts only rows that do not exist yet.", "begin;", ""]
    for r in recipes:
        missing = [l.name for l in r.lines if l.name not in catalog]
        if missing:
            raise ValueError(f"{r.slug}: unknown ingredients {missing}")
        lines.append(f"-- {r.name}")
        lines.append("with new_recipe as (\n  insert into public.curated_recipes(slug, name, description, category, cuisine, minutes, servings, taste, status, source)\n"
                     f"  values ({quote(r.slug)}, {quote(r.name)}, {quote(r.description)}, {quote(r.category)}, {quote(r.cuisine)}, "
                     f"{r.minutes}, {r.servings}, {quote(json.dumps(r.taste))}::jsonb, 'published', 'curated')\n"
                     "  on conflict (slug) do nothing returning id\n), lines as (\n"
                     "  insert into public.recipe_ingredients(recipe_id, ingredient_id, position, grams, display)\n"
                     "  select new_recipe.id, v.ingredient_id, v.position, v.grams, v.display from new_recipe, (values\n"
                     + ",\n".join(f"    ({ingredient_id(l.name)}, {i}, {l.grams}, {quote(l.display)})" for i, l in enumerate(r.lines, 1))
                     + "\n  ) as v(ingredient_id, position, grams, display) returning recipe_id\n)\n"
                     "insert into public.recipe_steps(recipe_id, position, body)\n"
                     "select new_recipe.id, v.position, v.body from new_recipe, (values\n"
                     + ",\n".join(f"  ({i}, {quote(s)})" for i, s in enumerate(r.steps, 1))
                     + "\n) as v(position, body);")
        lines.append("")
    lines.append("-- Compatibility edges: core ingredients used together in curated recipes.")
    for pair, edge in sorted(cooccurrence_edges(recipes, catalog).items(), key=lambda kv: sorted(kv[0])):
        a, b = sorted(pair)
        lines.append("insert into public.ingredient_compatibility(ingredient_a, ingredient_b, weight, relation_type, evidence) "
                     f"select least(x, y), greatest(x, y), {edge.weight}, 'co-occurrence', {quote(edge.evidence)} "
                     f"from (select {ingredient_id(a)} x, {ingredient_id(b)} y) ids on conflict do nothing;")
    lines.extend(["", "commit;", ""])
    return "\n".join(lines)


def main() -> None:
    out = ROOT / "supabase/seed/recipes.sql"
    out.write_text(build(), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
