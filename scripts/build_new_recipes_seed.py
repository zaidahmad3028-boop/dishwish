"""Generate supabase/seed/recipes_0002_more.sql: only the recipes added in api/engine/curated_more.py.

Compact on purpose (one JSON payload, one loop) so it can be pasted into the Supabase SQL Editor.
Safe on a live database: recipes are inserted only when their slug is new, edges only when the pair is new,
and nothing existing is updated or deleted. Run after migrations 0001-0010 and seed/recipes.sql.
"""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "api"))

from engine.curated_data import RECIPES  # noqa: E402
from engine.curated_more import MORE_RECIPES  # noqa: E402
from engine.data import TASTES, load_ingredients  # noqa: E402
from engine.suitability import bundled_recipes, cooccurrence_edges  # noqa: E402


def build() -> str:
    catalog = {i.name: i for i in load_ingredients()}
    new_slugs = {r[0] for r in MORE_RECIPES}
    recipes = [r for r in bundled_recipes() if r.slug in new_slugs]
    payload = []
    for r in recipes:
        missing = [l.name for l in r.lines if l.name not in catalog]
        if missing:
            raise ValueError(f"{r.slug}: unknown ingredients {missing}")
        payload.append({"slug": r.slug, "name": r.name, "description": r.description, "category": r.category,
                        "cuisine": r.cuisine, "minutes": r.minutes, "servings": r.servings, "taste": dict(r.taste),
                        "lines": [[l.name, l.grams, l.display] for l in r.lines], "steps": list(r.steps)})
    old = [r for r in bundled_recipes() if r.slug not in new_slugs]
    old_pairs = set(cooccurrence_edges(old, catalog))
    edges = [[*sorted(p), e.weight, e.evidence] for p, e in sorted(cooccurrence_edges(bundled_recipes(), catalog).items(),
                                                                     key=lambda kv: sorted(kv[0])) if p not in old_pairs]
    data = json.dumps({"recipes": payload, "edges": edges}, ensure_ascii=False, separators=(",", ":")).replace("'", "''")
    return f"""-- Generated by scripts/build_new_recipes_seed.py; do not edit by hand. {len(payload)} new recipes, {len(edges)} new edges.
-- Inserts only rows that do not exist yet; never updates or deletes.
do $seed$
declare
  d jsonb := '{data}'::jsonb;
  r jsonb; rid bigint; i int; missing text;
begin
  select string_agg(n, ', ') into missing from (
    select distinct l->>0 n from jsonb_array_elements(d->'recipes') r2, jsonb_array_elements(r2->'lines') l
    where not exists (select 1 from public.ingredients x where x.name = l->>0)) m;
  if missing is not null then raise exception 'Unknown ingredients: %', missing; end if;
  for r in select * from jsonb_array_elements(d->'recipes') loop
    insert into public.curated_recipes(slug, name, description, category, cuisine, minutes, servings, taste, status, source)
    values (r->>'slug', r->>'name', r->>'description', r->>'category', r->>'cuisine', (r->>'minutes')::int,
            (r->>'servings')::int, r->'taste', 'published', 'curated')
    on conflict (slug) do nothing returning id into rid;
    continue when rid is null;
    for i in 0 .. jsonb_array_length(r->'lines') - 1 loop
      insert into public.recipe_ingredients(recipe_id, ingredient_id, position, grams, display)
      select rid, x.id, i + 1, (r->'lines'->i->>1)::numeric, r->'lines'->i->>2
      from public.ingredients x where x.name = r->'lines'->i->>0;
    end loop;
    for i in 0 .. jsonb_array_length(r->'steps') - 1 loop
      insert into public.recipe_steps(recipe_id, position, body) values (rid, i + 1, r->'steps'->>i);
    end loop;
  end loop;
  insert into public.ingredient_compatibility(ingredient_a, ingredient_b, weight, relation_type, evidence)
  select least(a.id, b.id), greatest(a.id, b.id), (e->>2)::numeric, 'co-occurrence', e->>3
  from jsonb_array_elements(d->'edges') e
  join public.ingredients a on a.name = e->>0 join public.ingredients b on b.name = e->>1
  on conflict do nothing;
end $seed$;

select count(*) as published_recipes from public.curated_recipes where status = 'published';
"""


def main() -> None:
    out = ROOT / "supabase/seed/recipes_0002_more.sql"
    out.write_text(build(), encoding="utf-8")
    print(f"Wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
