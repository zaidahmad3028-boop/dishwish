// App imagery. Served from a Cloudflare R2 public bucket when VITE_IMAGE_BASE_URL is set
// (e.g. https://pub-xxxx.r2.dev); otherwise from the copies bundled in web/public/images.
// Keep the same folder layout in both places, e.g. kitchen/counter-hero.webp.
import { INGREDIENT_PHOTO_SLUGS, RECIPE_PHOTO_SLUGS } from './photoManifest';

const base = (import.meta.env.VITE_IMAGE_BASE_URL || '/images').replace(/\/+$/, '');

export const imageUrl = (path: string) => `${base}/${path.replace(/^\/+/, '')}`;

export const IMAGES = {
  kitchenHero: 'kitchen/counter-hero.webp',
} as const;

// Which recipes/ingredients have a photo (recipes/<slug>.webp, ingredients/<slug>.webp) is generated by
// scripts/fetch_images.py into photoManifest.ts.
const RECIPE_PHOTOS = new Set(RECIPE_PHOTO_SLUGS);
const INGREDIENT_PHOTOS = new Set(INGREDIENT_PHOTO_SLUGS);

// Same rule as the script: "Spring Onion (Hara Pyaz)" -> "spring-onion-hara-pyaz".
export const slugify = (name: string) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');

// An admin-set image_url wins; otherwise the bundled/R2 photo; otherwise null (the default picture is shown).
export const recipeImage = (slug: string, adminUrl?: string | null) =>
  adminUrl || (RECIPE_PHOTOS.has(slug) ? imageUrl(`recipes/${slug}.webp`) : null);

export const ingredientImage = (name: string, adminUrl?: string | null) => {
  const slug = slugify(name);
  return adminUrl || (INGREDIENT_PHOTOS.has(slug) ? imageUrl(`ingredients/${slug}.webp`) : null);
};

// The Kitchen's featured dishes (the owner's own photos), first and in this order, then the rest as given.
const FEATURED = ['chicken-karahi', 'chicken-biryani', 'chicken-qorma'];
export const photosFirst = <T extends { slug: string }>(items: T[]) => {
  const rank = (slug: string) => { const i = FEATURED.indexOf(slug); return i === -1 ? FEATURED.length : i; };
  return [...items].sort((a, b) => rank(a.slug) - rank(b.slug));
};
